// Mengembalikan fungsi terjemahan untuk bahasa yang sedang aktif.
// Jika key tidak ditemukan, key itu sendiri yang ditampilkan, sehingga mudah dikenali saat kurang.
export function useT() {
  const locale = useUiStore((s) => s.locale);
  return (key: string, vars?: Record<string, string | number>): string => {
    let text = dictionary[locale][key] ?? dictionary.en[key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.replace(`{${name}}`, String(value));
      }
    }
    return text;
  };
}